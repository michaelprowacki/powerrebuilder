# Lazy loading proxy for opcode table
class _OpcodeTableProxy:
    """Proxy object for lazy loading of opcode table."""

    def __getitem__(self, key):
        return _load_opcode_table()[key]

    def __iter__(self):
        return iter(_load_opcode_table())

    def __len__(self):
        return len(_load_opcode_table())

    def get(self, key, default=None):
        return _load_opcode_table().get(key, default)

    def keys(self):
        return _load_opcode_table().keys()

    def values(self):
        return _load_opcode_table().values()

    def items(self):
        return _load_opcode_table().items()


# Public API - lazily loaded
OPCODE_TABLE = _OpcodeTableProxy()


class OpcodeManager:
    """Manages PowerBuilder opcodes."""

    def __init__(self) -> None:
        """Initialize the OpcodeManager."""
        # Cache for version-specific opcode tables
        self._opcode_cache: dict[Any, dict[int, tuple[str, int, str | None]]] = {}
        # Reference to the global opcode mappings (lazy loaded)
        self._opcodes = OPCODES
        self._opcode_table = OPCODE_TABLE

    def get_opcode(self, code: int) -> str:
        result = self._opcodes.get(code, f"UNKNOWN_{code:02X}")
        return str(result)

    @staticmethod
    def get_opcode_table(version: Any) -> dict[int, tuple[str, int, str | None]]:
        """Get opcode table for a specific PowerBuilder version.

        Returns:
            Dictionary mapping opcode values to (name, length, hint) tuples
        """
        # Convert OPCODE_TABLE to the expected format
        result = {}
        for code, info in OPCODE_TABLE.items():
            result[code] = (info["name"], info["length"], info.get("stack_effect"))
        return result


def find_opcode_by_name(name: str) -> int | None:
    """Find opcode by name."""
    for code, opname in OPCODES.items():
        if str(opname) == name:
            return int(code)
    return None


def get_opcode_info(code: int) -> tuple[str, int, str | None] | None:
    """Get opcode information in decoder-expected format.

    Returns:
        Tuple of (mnemonic, length, operand_hint) or None if not found
    """
    info = OPCODE_TABLE.get(code)
    if info:
        return (info["name"], info["length"], info.get("stack_effect"))
    return None


def get_opcodes_for_version(_version: Any) -> dict[int, str]:
    """Get opcodes for a specific PowerBuilder version."""
    return dict(_load_opcodes())


def get_variant_info(code: int) -> dict[str, Any]:
    """Get variant information for an opcode."""
    info = OPCODE_TABLE.get(code, {})
    return {"category": info.get("category")}


def has_variants(code: int) -> bool:
    """Check if an opcode has variants."""
    # Check if this is part of a type-specific operation
    name = OPCODES.get(code, "")
    base_ops = [
        "ADD",
        "SUB",
        "MUL",
        "DIV",
        "ASSIGN",
        "PUSH",
        "POP",
        "EQ",
        "NEQ",
        "LT",
        "GT",
    ]
    return any(name.startswith(f"{op}_") for op in base_ops)


def get_opcode_name(code: int) -> str:
    """Get the name of an opcode."""
    result = OPCODES.get(code, f"UNKNOWN_{code:02X}")
    return str(result)


def get_opcode_length(code: int) -> int:
    """Get the length of an opcode instruction."""
    info = OPCODE_TABLE.get(code)
    return info["length"] if info else 1


